-- `WR-08` — بطاقةُ العرضِ الخاصّةُ لا تبقى بزرَّي «قبول/رفض» بعدَ موتِ عرضِها.
--
-- **المقيسُ (2026-10-12، قراءةٌ فقط):** كلُّ صفٍّ `offer` مُسلَّمٍ في `notification_outbox` يحملُ
-- `delivered_message_id`، ولا شيفرةَ تعدّلُ البطاقةَ إلّا حينَ ينقرُها السائق (`WR-08`، #507).
-- فالعرضُ الذي تنتهي مهلتُه، أو يسبقُ إليه سائقٌ آخر، أو يُلغى طلبُه، تبقى بطاقتُه بأزرارِها،
-- والخادمُ يرفضُ النقرةَ لكنَّ البطاقةَ توحي بعرضٍ متاح.
--
-- **القرار (ADR 0271):** عمودانِ على `notification_outbox`، بلا دالّةٍ ولا صلاحيّة:
--   ١) `offer_card_closed_at`: متى كُتبَ المآلُ على البطاقةِ وأُزيلَت أزرارُها.
--   ٢) `offer_card_close_attempts`: عدّادُ محاولاتِ التعديلِ العابرةِ الفاشلة؛ والشوطُ يكفُّ
--      بعدَ حدٍّ في الشيفرة.
-- وخطوةٌ في شوطِ `expire-offers:<city>` القائمِ تلتقطُ البطاقاتِ المسلَّمةَ غيرَ المغلقةِ التي
-- صارَ عرضُها `expired` أو `cancelled`، فتعدّلُها ثمَّ تعلّمُها.
--
-- **البطاقاتُ القديمة:** ما ليسَ عرضُه `pending` يُعلَّمُ مغلقًا هنا **دونَ تعديلِ رسالتِه**، فالنشرُ لا يمسُّ محادثاتِ
-- سائقينَ حقيقيّينَ بأثرٍ رجعيّ (كما في ADR 0270).
--
-- **بلا فهرس:** صفوفُ `offer` المسلَّمةُ غيرُ المغلقةِ قليلةٌ بطبيعتِها (تُغلَقُ خلالَ دقيقة)،
-- والقراءةُ مقيَّدةٌ بالمدينةِ وبالنوعِ وبحدّ؛ و`notification_outbox` فيه الفهرسُ القائمُ على
-- `offer_id`. وفهرسٌ جديدٌ على جدولٍ ساخنٍ كلفةُ كتابةٍ بلا عائدٍ مقيس.
--
-- **العودة:** حذفُ العمودين. والشيفرةُ السابقةُ لا تقرؤُهما.
-- =============================================================================

alter table notification_outbox
  add column if not exists offer_card_closed_at timestamptz,
  add column if not exists offer_card_close_attempts integer not null default 0;

update notification_outbox
   set offer_card_closed_at = now()
 where kind = 'offer'
   and offer_card_closed_at is null
   and not exists (
     select 1 from order_offers oo
      where oo.id = notification_outbox.offer_id and oo.status = 'pending'
   );
