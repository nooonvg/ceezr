-- - خطةٌ عامةٌ (بعدَ 5 تنفيذاتٍ — وهيَ عينُ الإنتاجِ): الاستعلامُ مُعلمٌ
--   (`kind = any($1)`) فلا يستطيعُ المخطِّطُ إثباتَ محمولِ **أيِّ** فهرسٍ
