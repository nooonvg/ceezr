-- ## لماذا لا تُسقَطُ الفهارسُ القديمةُ
--
-- عرفُ المستودعِ (رأسُ 20260909151000): إسقاطُ فهرسٍ قائمٍ قرارٌ يحتاجُ قياسَ
-- خططٍ على حجمِ إنتاجٍ وهو دَينٌ يُعلَنُ لا إسقاطٌ بالظنِّ. فهذان الفهرانِ
-- الجديدانِ يُنشآنِ بأسماءٍ جديدةٍ وتُتركُ القديمةُ في مكانِها (ميتةً زائدةً —
-- المخطِّطُ لا يختارُها للخطةِ العامةِ أصلًا لأنَّ محمولَها لا يُثبَتُ)،
-- وإسقاطُها لاحقًا بندٌ مستقلٌ بعدَ قياسٍ.
--
