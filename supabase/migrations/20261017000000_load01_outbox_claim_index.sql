-- ## لماذا هذه الهجرة
--
-- موجةُ القبولِ 50 (2026-10-17) كشفت عيبًا حقيقيًّا في السعةِ: طابورُ صندوقِ
-- الصادرِ تراكمَ (32,260 معلقًا مقابل 1,108 مسلَّمًا) وأقدمُ مهمةٍ بلغَ 376ث
-- (بروتوكولُ القبولِ P7: ≤ 120ث). التشخيصُ من خطةِ التنفيذِ (EXPLAIN) على
-- `claim_notification_delivery`:
--
-- - استعلامُ الالتقاطِ يفحصُ **تسلسليًّا** كلَّ الصفوفِ المعلقةِ (22 ألفًا)
--   ويفرزُها (`Seq Scan` + `Hash Anti Join` + `Sort`, ‏47ms عند 22 ألفِ صفٍّ
--   معلقٍ) لأنَّ فهرسَ الأولويةِ الجزئيَّ `notification_outbox_priority_due_idx`
--   يغطي قائمةَ أنواعٍ (8) **لم تعد تطابقُ** قائمةَ `v_ride_kinds` في الدالةِ
--   (14 نوعًا بعد إضافةِ `rider_trip_notice` و`driver_candidate_notice` و
--   `order_chat_message` ورسائلِ السلامةِ) — فلا يستطيعُ المخطِّطُ إثباتَ
--   احتواءِ محمولِ الفهرسِ لشرطِ الاستعلامِ فيسقطَهُ.
-- - الالتقاطُ نداءُ RPC **لكلِّ رسالةٍ**: كلُّ نداءٍ يدفعُ كاملَ فحصِ الجدولِ،
--   فكلَّما تراكمَ الطابورُ بطُؤَ الالتقاطُ فتراكمَ أكثرَ — حلقةُ انهيارٍ
--   كلاسيكيةٌ (O(N) لكل رسالة).
--
-- ## ما الذي تتغير
--
-- ١. يُعادُ بناءُ `notification_outbox_priority_due_idx` و
--    `notification_outbox_ride_cycle_due_idx` بمحمولٍ يطابقُ قائمةَ الأنواعِ
--    الحاليةَ حرفيًّا (14 نوعًا)، فيمكنُ المخطِّطُ استخدامَ الفهرسِ الجزئيِّ
--    لمسحِ المرشحينَ بترتيبِ الأولويةِ والإقلاعِ عندَ أولِ صفٍّ قابلٍ للالتقاط
--    (`LIMIT 1` + `NOT EXISTS` على فهرسِ الطلبِ) — O(log N) بدلَ O(N).
-- ٢. لا يتغيرُ سلوكُ الدالةِ ولا ضماناتُ الترتيبِ: نفسُ قائمةِ الأنواعِ،
--    ونفسُ قاعدةِ «أقدمُ رسالةٍ لكلِّ طلبٍ أولًا» (`NOT EXISTS` على
--    `(created_at, id)`)، ونفسُ `FOR UPDATE SKIP LOCKED`.
--
-- ## لماذا حذفٌ وإعادةُ بناءٍ لا `CREATE INDEX CONCURRENTLY`
--
-- الفهرسُ الجزئيُّ القديمُ يُستبدَلُ باسمٍ جديدٍ؛ `CONCURRENTLY` لا يعملُ داخلَ
-- معاملةٍ (والهجرُ تُطبَّقُ بمعاملةٍ ذرّيةٍ عبرَ قفلِ الهجراتِ) ولن يقبلَ
-- المخطِّطُ الفهرسَ القديمَ والجديدَ معًا بلا حذفٍ. الجدولُ في بيئةِ الاختبارِ
-- صغيرٌ (عشراتُ آلافِ الصفوف) فإعادةُ البناءِ لحظيةٌ.
--
