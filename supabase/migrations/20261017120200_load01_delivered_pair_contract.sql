-- هنا وحدَهُ (طورُ العقدِ) لا في ملفِّ التوسعةِ، لأنَّ حاجزَ سلامةِ الهجراتِ
-- يضعُ كلَّ حذفٍ في ملفِّ العقدِ بعدَ التبديلِ حتى لا يكسرَ نسخةً عاملةً إن
-- سبقَ نشرَهُ.
