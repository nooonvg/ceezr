alter table public.notification_outbox
  drop constraint if exists notification_delivered_pair;

-- `not valid`: القيدُ الجديدُ أوسعُ منَ القديمِ (كلُّ ما كانَ يفي يفي)، لكنَّ
-- القفلَ الحاجزَ على الجدولِ الحيِّ ثمنٌ لا يُدفعُ — فيُضافُ بلا مصادقةٍ
-- فوريةٍ ويُصادَقُ في طورِ التحققِ (20261017120300) بقفلٍ أخفَّ.
alter table public.notification_outbox
  add constraint notification_delivered_pair check (
    (status <> 'delivered')
    or (
      delivered_at is not null
      and (
        delivered_message_id is not null
        or delivered_channel = 'miniapp_board'
      )
    )
  ) not valid;

-- التراجعُ: إعادةُ القيدِ الأضيقِ (إسقاطُ الأوسعِ) لا تفقدُ بياناتٍ — الصفوفُ
-- المسلَّمةُ عبرَ اللوحِ تحملُ قناتَها المصرَّحةَ، وإن أُعيدَ القيدُ القديمُ
-- فلن يُقبَلَ تسليمُ لوحٍ جديدٌ حتى يُوسَّعَ ثانيةً.
