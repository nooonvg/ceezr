-- القيدُ القديمُ: الصفُّ المسلَّمُ لا بدَّ أن يحملَ معرّفَ رسالةٍ (بطاقةُ
-- تيليجرامَ). الجديدُ: أو قناةً مصرَّحةً `miniapp_board` — أي إيصالَ لوحٍ
-- موثَّقًا — وهوَ أوسعُ لا أضيقُ: كلُّ صفٍّ كانَ يفي بالقديمِ (معرّفُ رسالةٍ
