/**
 * الغرض: أصنافُ أولويّةِ المرورِ التجاريِّ تحتَ الضغطِ — **مصدرُ الحقيقةِ الواحدُ**
 *   لسؤالِ: أيُّ حركةٍ أحقُّ بالشوطِ وبفتحةِ الدلوِ حينَ يَضيقُ أحدُهما؟ البند
 *   `F6-07` (القسمُ ١٥ من `docs/ROADMAP-MASTER.md`).
 * الحالة: منفّذ فعلياً — 2026-09-09.
 * ينتمي إلى: packages/shared/config
 * يُستخدم من: `scripts/check-traffic-priority.ts`،
 *   `packages/application/scheduling/traffic-priority.ts`،
 *   `packages/infrastructure/notification/rate-aware-telegram-sender.ts`،
 *   `packages/infrastructure/notification/outbound-rate-bucket.ts`،
 *   و`supabase/migrations/20260909150000_f6_07_traffic_priority.sql` (مُقابَلةً بحاجزٍ).
 *
 * ## نصُّ القسمِ ١٥ حرفاً — والأصنافُ منه لا من ذوقٍ
 *
 * | الأولوية | ما يُحمى |
 * |---|---|
 * | **حرج** | SOS، حالة الرحلة النشطة، حالة الدفع، مطالبة الإسناد، مراحل الوصول والإنهاء |
 * | **مرتفع** | إنشاء الرحلة، تسليم العروض، استقبال المواقع |
 * | **متوسط** | التقييمات، تحديثات الدعم، الإشعارات العادية |
 * | **منخفض** | التحليلات، الخرائط الحرارية، البثّ الجماعي، التوصيات غير الجوهرية |
 *
 * وتكملتُه في القسمِ نفسِه: «عند تجاوز أي طابور حدّه: تُقلَّص الوظائف الثانوية،
 * ويؤجَّل البثّ غير الضروري، ويُخفَّض الاستقصاء، وتُحمى الرحلات النشطة والدفع
 * و SOS. الانهيار الشامل بسبب خدمة ثانوية هو **عيب معماري** لا حادث تشغيلي».
 *
 * ## لماذا أربعةُ أصنافٍ لا اثنانِ — ولماذا لا يكفي ما بُنيَ قبلَ هذا البندِ
 *
 * في المستودعِ سلفاً **حاكمانِ ثنائيّانِ** كلٌّ منهما صحيحٌ في موضعِه وقاصرٌ عن
 * هذا البندِ:
 *
 * - `SendPriority` (`critical | informational`) في `telegram-api-sender.ts` —
 *   يحكمُ **سقفَ المحاولاتِ** ومصيرَ الخنقِ الطويلِ لنداءٍ واحدٍ (`F6-04`).
 * - `deferrable` في `decideAdmission` (`F6-06`) — يحكمُ **بابَ الإيداعِ** حينَ
 *   يُشبَعُ الطابورُ.
 *
 * وكلاهما لا يُجيبُ السؤالَ الذي يُجيبُه هذا الملفُّ: **حينَ يقفُ عرضُ رحلةٍ
 * وبثٌّ جماهيريٌّ في الطابورِ نفسِه، أيُّهما يُلتقَطُ أوّلاً؟** الجوابُ قبلَ
 * `F6-07` كانَ «الأقدمُ» (`order by created_at`) — أي **الأسبقُ إيداعاً لا
 * الأحقُّ تسليماً**. فدفعةُ بثٍّ من ألفِ مستقبِلٍ أُودِعَت قبلَ ثانيةٍ تتقدَّمُ على
 * بلاغِ استغاثةٍ أُودِعَ الآنَ، **وكلُّ حدودِ `F6-06` سليمةٌ في تلكَ اللحظةِ**:
 * لا عمقٌ خُرِقَ ولا عمرٌ ولا موتى — ومع ذلك الاستغاثةُ خلفَ ألفِ صفٍّ. **وهذا
 * هوَ عينُ «الانهيارِ بسببِ خدمةٍ ثانويّةٍ» الذي يسمّيه القسمُ ١٥ عيباً معماريّاً.**
 *
 * ## الصنفُ صفةُ **نوعِ** الإشعارِ لا صفةُ صفٍّ ولا سياسةُ مدينةٍ
 *
 * ولذلكَ موضعُه الشيفرةُ لا `platform_settings` — **ولا يخالفُ القاعدةَ ٠.٣**:
 * القاعدةُ تمنعُ حفرَ **الأرقامِ القابلةِ للضبطِ** (مُدَدٍ، سقوفٍ، نِسَبٍ) في
 * الكودِ لأنَّها تختلفُ من مدينةٍ إلى مدينةٍ ويملكُها المشغِّلُ. وأنَّ **بلاغَ
 * الاستغاثةِ أحقُّ من إعلانٍ** ليسَ رقماً ولا سياسةَ مدينةٍ ولا يملكُ المشغِّلُ
 * قلبَه: لو صارَ صفّاً في إعدادٍ لأمكنَ لصفٍّ واحدٍ في مدينةٍ أن يضعَ `SOS` خلفَ
 * البثِّ — وذلكَ عطبُ سلامةٍ لا مرونةُ منتَجٍ.
 *
 * وهذا **غيرُ** قناةِ `F6-05` عن قصدٍ: القناةُ (`critical | in_app`) قرارُ منتَجٍ
 * يختلفُ بينَ مدينةٍ ومدينةٍ فسكنَ `notification_kind_policy` في القاعدةِ.
 * والصنفُ ههنا **رتبةٌ بنيويّةٌ** لا تختلفُ. ومن خلطَهما جعلَ إسكاتَ نوعٍ في
 * مدينةٍ يُغيِّرُ رتبتَه في مدينةٍ أخرى.
 *
 * ## ما يمنعُه الحاجزُ فعلاً
 *
 * أنَّ **نوعاً جديداً يُولَدُ بلا رتبةٍ**. لو أُضيفَ نوعٌ إلى `NOTIFICATION_KINDS`
 * ولم يُصنَّف ههنا سقطَ `scripts/check-traffic-priority.ts`، وسقطَ معَه تطابقُ
 * هذا الملفِّ مع دالّةِ `notification_kind_priority` في الهجرةِ — **فالطرفانِ
 * يُقابَلانِ لا يُصدَّقُ أحدُهما**. وافتراضُ المجهولِ عندَ التشغيلِ **`critical`**
 * (رتبةُ ١) لا `low`: الميلُ نحوَ الحمايةِ كما في `F6-05` (غيابُ سياسةٍ ⇒ يُرسَل)
 * وفي `F6-06` (حدٌّ معطوبٌ ⇒ مخروقٌ). فنسيانُ تصنيفِ نوعٍ يُنتِجُ **تقديمَه** لا
 * تأخيرَه، ويُكشَفُ في CI لا في حادثةٍ.
 *
 * ## ما لا يفعلُه هذا الملفُّ عن قصدٍ
 *
 * - **لا يُسقِطُ صفّاً ولا رسالةً أبداً.** الأولويّةُ **ترتيبٌ وتأجيلٌ** لا إعدامٌ —
 *   وهوَ الحدُّ نفسُه المُعلَنُ في `F6-06`.
 * - **لا يحملُ سقفاً ولا مُدّةً ولا عمقاً.** تلكَ في مواضعِها المُعلَنةِ
 *   (`platform_settings` لما يختلفُ بالمدينةِ، أو `DEFAULT_OUTBOUND_RATE_LIMITS` لما
 *   تملِكُه منصّةٌ خارجٌ). والرقمُ الوحيدُ ههنا حِصّةُ الدلوِ، ومُبرّرُ
 *   موضعِها معَها في موضعِ تعريفِها.
 * - **لا يُصنِّفُ وارِداً**. طابورُ الوارِدِ (`telegram_update_jobs`) صنفٌ واحدٌ
 *   لا أنواعَ فيه: كلُّ صفٍّ تحديثُ تلغرام لا يُعرَفُ مضمونُه قبلَ فتحِه، وترتيبُ
 *   ما لا يُعرَفُ تخمينٌ. فأولويّةُ الوارِدِ دَينٌ مُعلَنٌ في `ADR 0071` §٦ لا
 *   دعوى ههنا.
 */

import { NOTIFICATION_KINDS, type NotificationKind } from "./notification-kinds.ts";

/** الأصنافُ الأربعةُ بأسماءِ القسمِ ١٥ — والترتيبُ ههنا هوَ الرتبةُ نفسُها. */
export const TRAFFIC_PRIORITY_CLASSES = ["critical", "high", "medium", "low"] as const;

export type TrafficPriorityClass = (typeof TRAFFIC_PRIORITY_CLASSES)[number];

/**
 * الرتبةُ رقماً: **الأصغرُ أسبقُ**. وتُقرأُ في القاعدةِ بالأرقامِ نفسِها
 * (`notification_kind_priority`) لأنَّ `order by` على رقمٍ لا على نصٍّ — فلو
 * رُتِّبَ بالنصِّ لصارَ `critical < high < low < medium` أبجديّاً، وهوَ ترتيبٌ
 * يُقدِّمُ المنخفضَ على المتوسّطِ بلا أن يُلاحِظَه أحدٌ.
 */
export const TRAFFIC_PRIORITY_RANK: Readonly<Record<TrafficPriorityClass, number>> = {
  critical: 1,
  high: 2,
  medium: 3,
  low: 4,
};

/**
 * رتبةُ كلِّ نوعٍ من أنواعِ صندوقِ الصادرِ الأحدَ عشرَ — **قائمةٌ مغلقةٌ**،
 * وكلُّ سطرٍ فيها مردودٌ إلى سطرٍ من القسمِ ١٥ لا إلى تقديرٍ:
 *
 * - `safety_incident` ← **SOS** نصّاً. أوّلُ ما يُحمى في القسمَينِ ١٤ و١٥.
 * - `order_cancelled` ← **حالةُ الرحلةِ النشطةِ**: السائقُ المُسنَدُ يجبُ أن يعرفَ
 *   أنَّ الرحلةَ أُلغيَت، وتأخيرُه يُنتِجُ سائقاً يسيرُ إلى راكبٍ لا ينتظرُه.
 * - `negotiation_turn_opened` · `negotiation_turn_closed` · `negotiation_agreed`
 *   ← **مطالبةُ الإسنادِ** نصّاً: هذه رسائلُ مُهلةٍ لها مؤقّتٌ يجري
 *   (`unsubscribed_negotiate_seconds`)، فتأخيرُ الرسالةِ **يستهلكُ المهلةَ نفسَها**
 *   ويُسقِطُ الدورَ على مَن لم يرَ أنَّه دورُه. وهذا هوَ الفرقُ الحاسمُ عن أيِّ
 *   إشعارٍ آخرَ: **الوقتُ فيه جزءٌ من المعنى لا وصفٌ لجودةِ الخدمةِ.**
 * - `offer` ← **تسليمُ العروضِ** نصّاً (مرتفعٌ). وله مؤقّتٌ أيضاً، لكنَّ سقوطَ
 *   عرضٍ واحدٍ يُعالَجُ بإعادةِ التوزيعِ (`redispatch-searching`) بلا فقدِ حالةٍ،
 *   بخلافِ دورِ مطالبةٍ سقطَ.
 * - `wider_circle_opened` ← **تسليمُ العروضِ** كذلك: توسيعُ الدائرةِ خطوةُ
 *   بحثٍ عن سائقٍ، وتأخيرُها تأخيرُ الإسنادِ كلِّه.
 * - `no_driver_found` ← **إشعارٌ عاديٌّ** (متوسّطٌ): خبرُ نتيجةٍ لا فعلٌ يُنتظَرُ.
 * - `dispute_resolution` ← **تحديثاتُ الدعمِ** نصّاً (متوسّطٌ).
 * - `subscription_notice` ← **إشعارٌ عاديٌّ** (متوسّطٌ). **وليسَ «حالةَ الدفعِ»**:
 *   حالةُ الدفعِ الحرجةُ حركةُ معاملةٍ جاريةٍ يقفُ عليها إتمامُ فعلٍ، وهذا
 *   **إخبارٌ بحالةِ اشتراكٍ** بعدَ تمامِها — ومن رفعَه إلى الحرجِ رفعَ معَه بريدَ
 *   التجديدِ كلَّه فأفرغَ الصنفَ الحرجَ من معناه.
 * - `broadcast_recipient` ← **البثُّ الجماعيُّ** نصّاً (منخفضٌ). وهوَ المُنتِجُ
 *   الذي بُنيَ حدُّ المُنتِجِ في `F6-06` لأجلِه.
 * - `lost_item_report` ← **تحديثُ دعمٍ ذو قيمةٍ زمنيّةٍ** (متوسّطٌ): بلاغٌ إلى
 *   سائقٍ أن يفتّشَ سيّارتَهُ الآنَ. ليسَ استغاثةً ولا حالةَ رحلةٍ ولا مطالبةَ
 *   إسنادٍ ذا مؤقّتٍ يجري، فلا يُحمى حمايةَ الحرجِ ولا يُقدَّمَ تقديمَ المرتفعِ؛
 *   وليسَ في تتابعٍ سببيٍّ مع دورةِ الرحلةِ فيؤجَّلُ بأمانٍ عندَ الإشباعِ.
 * - `rider_trip_notice` ← **حالةُ رحلةٍ نشطةٍ** (حرجٌ، `WR-15`): قبولُ السائقِ
 *   أو وصولُه أو بدءُ الرحلةِ أو إكمالُها، والراكبُ ينتظرُها الآن.
 * - `driver_candidate_notice` ← **مطالبةُ إسنادٍ لها مؤقّتٌ يجري** (حرجٌ، `WR-09`):
 *   مآلُ قبولِ السائقِ بعدَ قرارِ الراكب، والسائقُ ينتظرُه ليتحرّكَ أو ينصرف.
 */
export const NOTIFICATION_KIND_PRIORITY: Readonly<Record<NotificationKind, TrafficPriorityClass>> =
  {
    safety_incident: "critical",
    order_cancelled: "critical",
    negotiation_turn_opened: "critical",
    negotiation_turn_closed: "critical",
    negotiation_agreed: "critical",
    rider_trip_notice: "critical",
    driver_candidate_notice: "critical",
    offer: "high",
    wider_circle_opened: "high",
    no_driver_found: "medium",
    dispute_resolution: "medium",
    subscription_notice: "medium",
    lost_item_report: "medium",
    safety_resolution_closed: "medium",
    safety_resolution_blocked: "medium",
    broadcast_recipient: "low",
  };

/**
 * رتبةُ نوعٍ **بالاسمِ لا بالنوعِ الساكنِ**: تُنادى بنصٍّ آتٍ من القاعدةِ، فلا
 * تفترضُ أنَّ الوارِدَ من الأنواعِ المعروفةِ. والمجهولُ `critical` — الميلُ نحوَ
 * الحمايةِ لا نحوَ التأخيرِ، والحاجزُ في CI هوَ من يمنعُ بقاءَ المجهولِ مجهولاً.
 */
export function priorityClassOfKind(kind: string): TrafficPriorityClass {
  const known = NOTIFICATION_KINDS.find((entry) => entry === kind);
  if (known === undefined) return "critical";
  return NOTIFICATION_KIND_PRIORITY[known];
}

/** الرتبةُ رقماً لنوعٍ بالاسمِ — الشكلُ الذي تُقابِلُه دالّةُ القاعدةِ. */
export function priorityRankOfKind(kind: string): number {
  return TRAFFIC_PRIORITY_RANK[priorityClassOfKind(kind)];
}

/**
 * أيُقبَلُ تأجيلُ هذا الصنفِ عندَ الإشباعِ؟ **الحرجُ والمرتفعُ لا يُؤجَّلانِ**:
 * تأجيلُ عرضٍ له مؤقّتٌ يجري تأجيلٌ إلى ما بعدَ انتهائِه، وذلكَ إسقاطٌ بالحسابِ
 * لا تهدئةٌ. والمتوسّطُ والمنخفضُ يُؤجَّلانِ — وهوَ نصُّ القسمِ ١٥: «تُقلَّص
 * الوظائف الثانوية، ويؤجَّل البثّ غير الضروري».
 */
export function isDeferrableClass(priority: TrafficPriorityClass): boolean {
  return priority === "medium" || priority === "low";
}

/**
 * جسرٌ إلى الحاكمِ الثنائيِّ القائمِ في المُرسِلِ (`F6-04`) — **جسرٌ لا تكرارٌ**:
 * سقفُ المحاولاتِ ومصيرُ الخنقِ الطويلِ يبقيانِ حيثُ هما، ويُشتقُّ مدخلُهما من
 * الرتبةِ بدلاً من أن يُخمِّنَه كلُّ موضعِ نداءٍ. فالحرجُ والمرتفعُ `critical`،
 * والمتوسّطُ والمنخفضُ `informational`.
 *
 * ولماذا يُطابِقُ التقسيمَ نفسَه الذي يُطابِقُه `isDeferrableClass`: لأنَّ السؤالَ
 * واحدٌ في جوهرِه — «أيَحتملُ هذا الصنفُ الانتظارَ؟» — والفصلُ في دالّتَينِ
 * لأنَّ **موضعَ الإنفاذِ** مختلفٌ (بابُ الإيداعِ في الطابورِ، وسقفُ المحاولاتِ في
 * النداءِ)، فلو اختلفَ الجوابُ يوماً في أحدِهما اختلفَ فيه وحدَه بلا جراحةٍ.
 */
export function sendPriorityOfClass(priority: TrafficPriorityClass): "critical" | "informational" {
  return priority === "critical" || priority === "high" ? "critical" : "informational";
}

/**
 * **الحِصّةُ المحفوظةُ في دلوِ الصادرِ**: النسبةُ العُظمى من الحدِّ العالميِّ التي
 * يجوزُ للحركةِ **المُحتمِلةِ للانتظارِ** (المتوسّطِ والمنخفضِ) أن تستهلكَها،
 * فالبقيّةُ محفوظةٌ لا تُنالُ إلّا بحرجٍ أو مرتفعٍ.
 *
 * ولماذا **حِصّةٌ** لا انتظارٌ أطولُ للحرجِ: الانتظارُ حكمُ الخاسرِ بعدَ فواتِ
 * الفتحةِ، والحِصّةُ تمنعُ فواتَها ابتداءً. دفعةُ بثٍّ من ألفِ صفٍّ تستهلكُ الدلوَ
 * كلَّه في ثوانٍ، فالحرجُ الذي يجيءُ بعدَها لا يجدُ ما ينتظرُه — يجدُ طابوراً
 * يتجدَّدُ أمامَه. فبحجزِ نصيبٍ يبقى للحرجِ فتحةٌ **في اللحظةِ نفسِها** التي
 * يمتلئُ فيها الدلوُ بغيرِه.
 *
 * **وموضعُها الشيفرةُ لا `platform_settings` — ولا تخالفُ القاعدةَ ٠.٣:** الدلوُ
 * الذي تُقسَمُ حِصّتُه **دلوُ البوتِ كلِّه لا دلوُ مدينةٍ** (`global` في
 * `outbound-rate-bucket.ts`)، فإعدادٌ لكلِّ مدينةٍ لا معنى له على مورِدٍ
 * مُشترَكٍ: أيُّ مدينةٍ يُقرأُ إعدادُها حينَ يُرسَلُ إلى محادثةٍ واحدةٍ من مدينةٍ
 * أخرى؟ ومن أجابَ «أيَّ واحدٍ» أعطى مدينةً واحدةً حقَّ إلغاءِ الحجزِ على
 * الجميعِ. فهيَ من جنسِ `DEFAULT_OUTBOUND_RATE_LIMITS` نفسِه — حدُّ منصّةٍ تقنيّةٍ
 * لا سياسةُ مشغِّلٍ — وتُمرَّرُ وسيطاً للدلوِ في الاختبارِ ولمن أرادَ معايرةً
 * بإعدادِ نشرٍ، فلا تُحفَرُ في موضعِ الإنفاذِ.
 *
 * و`0.8` تُبقي خُمسَ الحدِّ — خمسَ فتحاتٍ في الثانيةِ من خمسٍ وعشرينَ — محفوظاً
 * للحرجِ والمرتفعِ حتّى في أسوأِ دفعةِ بثٍّ.
 */
export const DEFAULT_LOW_PRIORITY_BUCKET_SHARE = 0.8;

/**
 * الجسرُ في الاتّجاهِ المُعاكسِ: من الحاكمِ الثنائيِّ عندَ حدِّ النقلِ إلى صنفٍ
 * يفهمُه الدلوُ. **تقريبٌ مُعلَنٌ لا تخمينٌ**: الدلوُ لا يُفرِّقُ بينَ الحرجِ
 * والمرتفعِ (كلاهما يرى الحدَّ كلَّه) ولا بينَ المتوسّطِ والمنخفضِ (كلاهما يرى
 * الحصّةَ)، فالثنائيُّ `critical|informational` يحملُ كلَّ ما يحتاجُه الدلوُ ولا
 * يُفقَدُ بالتحويلِ شيءٌ يستعملُه. ولذلكَ يُردُّ `medium` لا `low`: `low` صحيحٌ
 * حسابيّاً اليومَ ولكنّه ادّعاءُ تصنيفٍ لا نعرفُه، ولو فُصِلَ المنخفضُ يوماً عن
 * المتوسّطِ لصارَ ذلك الادّعاءُ خطأً صامتاً.
 *
 * والغيابُ يُقرأُ `critical`: مُنادٍ لم يُصنِّف يبقى كما كانَ قبلَ `F6-07`.
 */
export function bucketClassOfSendPriority(
  priority: "critical" | "informational" | undefined,
): TrafficPriorityClass {
  return priority === "informational" ? "medium" : "critical";
}

/**
 * الحصّةُ مقروءةً بأمانٍ: خارجُ المجالِ `(0, 1)` — أو `NaN` أو غيابٌ — يُقرأُ
 * **الافتراضَ** لا «بلا حِصّةٍ». وهوَ الميلُ نفسُه الذي في `F6-06`: إعدادٌ معطوبٌ
 * لا يُطفئُ حاجزاً.
 */
export function lowPriorityShareOrDefault(value: number | null | undefined): number {
  if (typeof value !== "number" || !Number.isFinite(value)) {
    return DEFAULT_LOW_PRIORITY_BUCKET_SHARE;
  }
  if (value <= 0 || value >= 1) return DEFAULT_LOW_PRIORITY_BUCKET_SHARE;
  return value;
}

/**
 * الحدُّ الفعليُّ لصنفٍ في دلوٍ حدُّه العالميُّ `limit`. **الحرجُ والمرتفعُ يريانِ
 * الحدَّ كلَّه**، والمتوسّطُ والمنخفضُ يريانِ الحصّةَ — وهوَ التقسيمُ نفسُه الذي
 * يردُّه `sendPriorityOfClass`، فلا حاكمَ ثالثٌ يُبتدَعُ في المُرسِلِ.
 *
 * ولماذا المرتفعُ معَ الحرجِ ههنا: العرضُ ومطالبةُ الإسنادِ كلاهما بمؤقّتٍ يجري،
 * وحجزُ الدلوِ عنهما تأخيرٌ يُبطِلُهما لا يُهدّئُهما. والتمييزُ بينَهما موضعُه
 * **ترتيبُ الطابورِ** (`notification_kind_priority`) لا حِصّةُ الدلوِ.
 *
 * وبقاءُ فتحةٍ واحدةٍ على الأقلِّ لغيرِ الحرجِ مقصودٌ: حِصّةٌ تُقرَّبُ إلى صفرٍ
 * تُحوِّلُ «تأجيلاً» إلى «إعدامٍ»، وهوَ ما لا يفعلُه هذا البندُ.
 */
export function effectiveBucketLimit(
  limit: number,
  priority: TrafficPriorityClass,
  share: number = DEFAULT_LOW_PRIORITY_BUCKET_SHARE,
): number {
  if (!Number.isFinite(limit) || limit <= 0) return 0;
  if (priority === "critical" || priority === "high") return Math.trunc(limit);
  const allowed = Math.floor(limit * lowPriorityShareOrDefault(share));
  return Math.max(1, Math.min(Math.trunc(limit), allowed));
}
